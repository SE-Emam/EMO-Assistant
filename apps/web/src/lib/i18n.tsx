const dictionaries: Record<Language, Record<string, string>> = { en, ar };

let activeLocale = "en";
let activeLanguage: Language = "en";

export function getStoredLanguage(): Language {
  try {
    const stored = localStorage.getItem(KEY);
    if (stored === "en" || stored === "ar") return stored;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("ar") ? "ar" : "en";
}

/** Applies language, direction and locale before the first render. */
export function initLanguage(): Language {
  const language = getStoredLanguage();
  applyLanguage(language);
  return language;
}

function applyLanguage(language: Language): void {
  activeLocale = LOCALES[language];
  activeLanguage = language;
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  try {
    localStorage.setItem(KEY, language);
  } catch {
    /* storage unavailable */
  }
}

export const locale = () => activeLocale;

/** Non-hook translation for helpers such as date formatting. */
export function translate(key: string, vars?: Record<string, string | number>): string {
  const template = dictionaries[activeLanguage][key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match));
}

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: Translate;
  locale: string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => getStoredLanguage());
  const setLanguage = useCallback((next: Language) => {
    applyLanguage(next);
    setLanguageState(next);
  }, []);
  useEffect(() => {
    applyLanguage(language);
  }, [language]);
  const t = useCallback<Translate>(
    (key, vars) => {
      const template = dictionaries[language][key] ?? en[key] ?? key;
      if (!vars) return template;
      return template.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match));
    },
    [language],
  );
  const value = useMemo(() => ({ language, setLanguage, t, locale: LOCALES[language] }), [language, setLanguage, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}
